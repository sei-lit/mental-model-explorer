import { mkdtempSync, readdirSync, statSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { GraphIndex } from '../src/core/model/graphIndex'
import { miniGraph } from '../src/core/testing/miniGraph'
import { MockBriefGenerator, type BriefGenerator } from '../src/core/understanding/briefGenerator'
import type { ModuleDossier } from '../src/core/understanding/dossier'
import { ModuleBriefService, NotAModuleError } from './moduleBriefs'

const index = new GraphIndex(miniGraph())

class CountingGenerator implements BriefGenerator {
  readonly kind = 'claude-cli' as const
  calls = 0
  constructor(private readonly output: (dossier: ModuleDossier) => Promise<unknown> = (dossier) => new MockBriefGenerator().generate(dossier)) {}
  generate(dossier: ModuleDossier) {
    this.calls += 1
    return this.output(dossier)
  }
}

const newCacheDir = () => join(mkdtempSync(join(tmpdir(), 'mme-briefs-')), 'briefs')

describe('ModuleBriefService', () => {
  it('generates a brief once and serves later requests, even from a new server, from the disk cache', async () => {
    const cacheDir = newCacheDir()
    const generator = new CountingGenerator()
    const first = await new ModuleBriefService(index, () => null, generator, 'sonnet', cacheDir).brief('mod.Screen')
    const again = await new ModuleBriefService(index, () => null, generator, 'sonnet', cacheDir).brief('mod.Screen')

    expect(generator.calls).toBe(1)
    expect(first.cached).toBe(false)
    expect(again).toMatchObject({ cached: true, hash: first.hash, brief: first.brief })
  })

  it('writes the cache so that only the user can read it', async () => {
    const cacheDir = newCacheDir()
    await new ModuleBriefService(index, () => null, new CountingGenerator(), 'sonnet', cacheDir).brief('mod.Screen')

    expect(statSync(cacheDir).mode & 0o777).toBe(0o700)
    const [file] = readdirSync(cacheDir)
    expect(statSync(join(cacheDir, file!)).mode & 0o777).toBe(0o600)
  })

  it('does not reuse a brief generated by another model', async () => {
    const cacheDir = newCacheDir()
    const generator = new CountingGenerator()
    const sonnet = await new ModuleBriefService(index, () => null, generator, 'sonnet', cacheDir).brief('mod.Screen')
    const opus = await new ModuleBriefService(index, () => null, generator, 'opus', cacheDir).brief('mod.Screen')

    expect(generator.calls).toBe(2)
    expect(opus.hash).not.toBe(sonnet.hash)
  })

  it('does not cache malformed output, so the next request generates again', async () => {
    const cacheDir = newCacheDir()
    const generator = new CountingGenerator(async () => ({ purpose: 'not a brief' }))
    const service = new ModuleBriefService(index, () => null, generator, 'sonnet', cacheDir)

    await expect(service.brief('mod.Screen')).rejects.toThrow(/要約の形式/)
    expect(service.cachedBrief('mod.Screen')).toBeNull()
  })

  it('shares one generation between concurrent requests for the same module', async () => {
    const generator = new CountingGenerator()
    const service = new ModuleBriefService(index, () => null, generator, null, null)
    await Promise.all([service.brief('mod.Screen'), service.brief('mod.Screen')])

    expect(generator.calls).toBe(1)
  })

  it('refuses ids that are not modules', () => {
    const service = new ModuleBriefService(index, () => null, new CountingGenerator(), null, null)
    expect(() => service.dossier('type.VM')).toThrow(NotAModuleError)
    expect(() => service.dossier('missing')).toThrow(NotAModuleError)
  })
})
