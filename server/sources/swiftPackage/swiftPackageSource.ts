import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { basename, join, relative, resolve, sep } from 'node:path'
import type { Claim, GraphEdge, GraphNode, ProjectGraph } from '../../../src/core/model/graph'
import type { ProjectSource } from '../../../src/data/projectSource'
import { deriveFlows, resolveCalls, type EntryKind, type FunctionFacts, type TypeFacts, type TypeResolver } from '../common/callGraph'
import { SWIFT_LAYERS } from './layers'
import { readModuleKinds, type ModuleKindCatalog } from './moduleKinds'
import { parseManifest, type ManifestTarget } from './packageManifest'
import { parseSwiftFile, type SwiftDeclaration, type SwiftFile, type SwiftFunction, type SwiftMember, type SwiftReference } from './swiftParser'

const SKIPPED_DIRECTORIES = new Set(['Generated', 'Resources', 'Preview Content'])
const LIFECYCLE_NAME = /^(did[A-Z]|on[A-Z]|handle|viewDid|viewWill|load|refresh|reload|retry|start|task|submit|send)/
const ENTRY_LAYERS = new Set(['ios.feature', 'ios.app'])
const GENERATED_MARKER = /Generated by|swagger-codegen|openapi-generator|DO NOT EDIT/i

export interface SwiftPackageOptions {
  /** Evidence and code paths are relative to it. Defaults to the package directory. */
  repoRoot?: string
  /** Types of another language that a binary module exposes: simple name → node id. */
  bridge?: { moduleName: string; types: ReadonlyMap<string, string> }
}

interface SourceFile {
  path: string
  /** Path relative to the repository root. */
  repoPath: string
  /** First-level directory below the target's sources; null for files directly in it. */
  directory: string | null
  parsed: SwiftFile
}

interface TargetData {
  manifest: ManifestTarget
  layerId: string | null
  files: SourceFile[]
  /** Machine-generated sources: their types are listed, their members are not. */
  generated: boolean
  /** Top-level types by name. */
  types: Map<string, TypeEntry>
}

interface Contribution {
  file: SourceFile
  declaration: SwiftDeclaration
  resolve: TypeResolver
}

/** A type node: one primary declaration plus same-target extensions, or an extension of a type that is not in the target. */
interface TypeEntry {
  id: string
  target: TargetData
  /** Name in the target: the type name, or the extended type for extension nodes. */
  name: string
  flavor: SwiftDeclaration['flavor']
  extensionOf: string | null
  contributions: Contribution[]
}

const observed = (text: string, source: string): Claim => ({ text, provenance: 'observed', source })

/** Reads a Swift package whose targets are declared in Package.swift: modules from the manifest, types from the .swift sources. */
export class SwiftPackageProjectSource implements ProjectSource {
  private readonly repoRoot: string

  constructor(
    private readonly packageDir: string,
    private readonly options: SwiftPackageOptions = {},
  ) {
    this.repoRoot = options.repoRoot ?? packageDir
  }

  async load(): Promise<ProjectGraph> {
    const manifestPath = join(this.packageDir, 'Package.swift')
    const manifest = parseManifest(readFileSync(manifestPath, 'utf8'))
    const manifestRepoPath = this.repoPath(manifestPath)
    const docsPath = join(this.packageDir, '..', 'docs', 'architecture', 'module-kinds.md')
    const catalog = readModuleKinds(docsPath)
    const docsRepoPath = this.repoPath(resolve(docsPath))

    const targets = manifest.targets.map((target) => this.readTarget(target, catalog))
    const byName = new Map(targets.map((target) => [target.manifest.name, target]))
    const entries = collectTypes(targets, byName)

    const nodes: GraphNode[] = []
    const edges = new Map<string, GraphEdge>()
    const addEdge = (edge: GraphEdge): void => {
      if (edge.source !== edge.target && !edges.has(edge.id)) edges.set(edge.id, edge)
    }

    nodes.push({ id: 'ios', kind: 'project', name: manifest.packageName ?? basename(this.packageDir), parentId: null, summary: 'Swift Package Manager のパッケージ。' })
    const groups = [...new Set(targets.map((target) => target.manifest.group ?? 'other'))].sort()
    for (const group of groups) {
      nodes.push({ id: `ios:group:${group}`, kind: 'package', name: group, parentId: 'ios', summary: `TargetGroup .${group} のターゲット群。` })
    }

    for (const target of targets) {
      const { name } = target.manifest
      const group = target.manifest.group ?? 'other'
      const kind = target.manifest.kind === 'source' ? catalog.kindOf(name, group) : null
      const claim = (text: string): Claim => ({ text, provenance: 'inferred', source: docsRepoPath })
      nodes.push({
        id: `ios:module:${name}`,
        kind: 'module',
        name,
        parentId: `ios:group:${group}`,
        summary: kind?.creation ?? (target.manifest.kind === 'binary' ? `バイナリターゲット ${name}（ソースなし）` : `Swift ターゲット ${name}`),
        ...(target.layerId ? { layer: target.layerId } : {}),
        ...(kind ? { responsibility: claim(kind.creation), role: claim(`種別: ${kind.name}（命名と TargetGroup から推定）`) } : {}),
      })
      for (const dependency of target.manifest.dependencies) {
        addEdge({
          id: `ios:dep:${name}->${dependency.target}`,
          source: `ios:module:${name}`,
          target: `ios:module:${dependency.target}`,
          relation: 'depends_on',
          evidence: observed(dependency.text, `${manifestRepoPath}:${dependency.line}`),
        })
      }
    }

    const typeFacts: TypeFacts[] = []
    const functionFacts: FunctionFacts[] = []
    const displayNames = new Map<string, string>()
    const entryKinds = new Map<string, EntryKind>()
    const functionIds = new Map<SwiftFunction, string>()

    for (const target of targets) {
      const moduleId = `ios:module:${target.manifest.name}`
      const directories = [...new Set(target.files.map((file) => file.directory).filter((directory): directory is string => directory !== null))].sort()
      const namespaces = directories.length >= 2
      if (namespaces) {
        for (const directory of directories) {
          nodes.push({ id: `ios:ns:${target.manifest.name}/${directory}`, kind: 'namespace', name: directory, parentId: moduleId, summary: `ディレクトリ ${directory}` })
        }
      }
      const parentOf = (file: SourceFile): string => (namespaces && file.directory !== null ? `ios:ns:${target.manifest.name}/${file.directory}` : moduleId)
      const entryAllowed = target.layerId !== null && ENTRY_LAYERS.has(target.layerId)
      const overloads = new Map<string, number>()
      const memberId = (base: string): string => {
        const count = (overloads.get(base) ?? 0) + 1
        overloads.set(base, count)
        return count === 1 ? base : `${base}#${count}`
      }

      for (const entry of [...entries.byTarget(target)].sort((a, b) => a.id.localeCompare(b.id))) {
        const primary = entry.contributions[0] as Contribution
        const isExtension = entry.extensionOf !== null
        const typeLabel = `${target.manifest.name}.${entry.name}`
        const members = entry.contributions.flatMap((contribution) => contribution.declaration.members.map((member) => ({ member, contribution })))
        const summary = primary.declaration.summary ?? (isExtension ? `extension ${entry.name}` : `${entry.flavor} ${entry.name}`)
        nodes.push({
          id: entry.id,
          kind: 'type',
          name: isExtension ? `extension ${entry.name}` : entry.name,
          parentId: parentOf(primary.file),
          flavor: entry.flavor,
          summary,
          ...(members.length === 0 && !target.generated
            ? { code: { language: 'swift' as const, path: primary.file.repoPath, startLine: primary.declaration.startLine, text: primary.declaration.text } }
            : {}),
        })

        const propertyTypes = new Map<string, string>()
        const methods = new Map<string, string[]>()
        const initParameterTypes: Array<[string, string]> = []
        for (const { member, contribution } of members) {
          const id = memberId(`${member.kind === 'method' ? 'ios:method' : 'ios:prop'}:${typeLabel}.${member.name}`)
          nodes.push({
            id,
            kind: member.kind,
            name: member.name,
            parentId: entry.id,
            summary: member.signature,
            code: { language: 'swift', path: contribution.file.repoPath, startLine: member.startLine, text: member.text },
          })
          displayNames.set(id, `${entry.name}.${member.name}`)
          // A stored closure is called like a method; this repository's Repository types are bundles of closures.
          if (member.keyword === 'func' || (member.kind === 'property' && member.isClosure)) {
            methods.set(member.name, [...(methods.get(member.name) ?? []), id])
          }
          if (member.kind === 'property' && member.declaredType && !propertyTypes.has(member.name)) propertyTypes.set(member.name, member.declaredType)
          if (member.keyword === 'init') {
            for (const parameter of member.parameters) if (parameter.type) initParameterTypes.push([parameter.name, parameter.type])
          }
          if (member.calls.length > 0 && (member.kind === 'method' || member.hasBody)) {
            functionFacts.push(functionFactsOf(id, entry.id, contribution, member))
            if (entryAllowed) {
              const kind = entryKindOf(member)
              if (kind) entryKinds.set(id, kind)
            }
          }
        }
        for (const [name, type] of initParameterTypes) if (!propertyTypes.has(name)) propertyTypes.set(name, type)

        const supertypeIds = new Set<string>()
        for (const contribution of entry.contributions) {
          for (const inherited of contribution.declaration.inherited) {
            const resolved = resolveQualified(inherited, contribution.resolve, byName)
            if (resolved) supertypeIds.add(resolved)
          }
        }
        typeFacts.push({
          id: entry.id,
          isAbstract: entry.flavor === 'protocol',
          propertyTypes,
          methods,
          supertypeIds: [...supertypeIds],
          resolveType: (name) => entry.contributions.map((contribution) => contribution.resolve(name)).find((id) => id !== null) ?? null,
        })
      }

      for (const file of target.files) {
        const parent = parentOf(file)
        for (const fn of file.parsed.functions) {
          const id = memberId(`ios:fn:${target.manifest.name}.${fn.name}`)
          nodes.push({ id, kind: 'method', name: fn.name, parentId: parent, summary: fn.signature, code: { language: 'swift', path: file.repoPath, startLine: fn.startLine, text: fn.text } })
          functionIds.set(fn, id)
          displayNames.set(id, fn.name)
          if (fn.calls.length > 0) {
            functionFacts.push({
              nodeId: id,
              ownerTypeId: null,
              path: file.repoPath,
              localTypes: fn.localTypes,
              calls: fn.calls,
              resolveType: entries.resolverOf(target, file),
            })
          }
          if (entryAllowed) entryKinds.set(id, 'other')
        }
      }
    }

    // Edges between types and from top-level functions to the types they mention.
    for (const entry of entries.all()) {
      const linked = new Set<string>([entry.id])
      const bridged = new Set<string>()
      for (const contribution of entry.contributions) {
        const { declaration, file } = contribution
        const evidenceSource = (line: number): string => `${file.repoPath}:${line}`
        if (entry.extensionOf !== null) {
          const extended = resolveQualified(entry.extensionOf, contribution.resolve, byName)
          if (extended && !linked.has(extended)) {
            linked.add(extended)
            addEdge({ id: `ios:extends:${entry.id}->${extended}`, source: entry.id, target: extended, relation: 'depends_on', evidence: observed(declaration.header, evidenceSource(declaration.line)) })
          }
        }
        for (const inherited of declaration.inherited) {
          const target = resolveQualified(inherited, contribution.resolve, byName)
          if (!target || linked.has(target)) continue
          linked.add(target)
          addEdge({ id: `ios:impl:${entry.id}->${target}`, source: entry.id, target, relation: 'implements', evidence: observed(declaration.header, evidenceSource(declaration.line)) })
        }
        for (const reference of declaration.references) {
          this.referenceEdge(entry.id, reference, file, contribution.resolve, linked, bridged, addEdge)
        }
      }
    }
    for (const target of targets) {
      for (const file of target.files) {
        const resolveType = entries.resolverOf(target, file)
        for (const fn of file.parsed.functions) {
          const id = functionIds.get(fn) as string
          const linked = new Set<string>()
          const bridged = new Set<string>()
          for (const reference of fn.references) this.referenceEdge(id, reference, file, resolveType, linked, bridged, addEdge)
        }
      }
    }

    const calls = resolveCalls(typeFacts, functionFacts).map((edge) => ({ ...edge, id: `ios:${edge.id}` }))
    for (const edge of calls) addEdge(edge)
    const flows = deriveFlows(calls, {
      entryKind: (nodeId) => entryKinds.get(nodeId) ?? null,
      nameOf: (nodeId) => displayNames.get(nodeId) ?? nodeId,
    }).map((flow) => ({ ...flow, id: `ios:${flow.id}` }))

    return { rootId: 'ios', layers: SWIFT_LAYERS, nodes, edges: [...edges.values()], flows }
  }

  private referenceEdge(
    from: string,
    reference: SwiftReference,
    file: SourceFile,
    resolveType: TypeResolver,
    linked: Set<string>,
    bridged: Set<string>,
    addEdge: (edge: GraphEdge) => void,
  ): void {
    const target = resolveType(reference.name)
    const source = `${file.repoPath}:${reference.line}`
    if (target) {
      if (linked.has(target)) return
      linked.add(target)
      addEdge({ id: `ios:ref:${from}->${target}`, source: from, target, relation: 'depends_on', evidence: observed(`${reference.name} を参照`, source) })
      return
    }
    const bridge = this.options.bridge
    const kotlinId = bridge?.types.get(reference.name)
    if (!bridge || !kotlinId || bridged.has(kotlinId) || !file.parsed.imports.some((entry) => entry.module === bridge.moduleName)) return
    bridged.add(kotlinId)
    addEdge({
      id: `ios:bridge:${from}->${kotlinId}`,
      source: from,
      target: kotlinId,
      relation: 'depends_on',
      evidence: { provenance: 'inferred', text: `${reference.name} を参照（${bridge.moduleName} 経由。名前の一致で推定）`, source },
    })
  }

  private readTarget(manifest: ManifestTarget, catalog: ModuleKindCatalog): TargetData {
    const layerId = manifest.kind === 'source' ? catalog.layerOf(manifest.name, manifest.group ?? 'other') : null
    const directory = join(this.packageDir, manifest.path)
    const sources = manifest.kind === 'source' ? swiftFiles(directory) : []
    const generated = isGenerated(sources)
    const files = sources.map((path): SourceFile => {
      const relativeToTarget = relative(directory, path).split(sep)
      return {
        path,
        repoPath: this.repoPath(path),
        directory: relativeToTarget.length > 1 ? (relativeToTarget[0] as string) : null,
        parsed: parseSwiftFile(readFileSync(path, 'utf8'), { members: !generated }),
      }
    })
    return { manifest, layerId, files, generated, types: new Map() }
  }

  private repoPath(path: string): string {
    return relative(this.repoRoot, path).split(sep).join('/')
  }
}

interface TypeIndex {
  all(): TypeEntry[]
  byTarget(target: TargetData): TypeEntry[]
  resolverOf(target: TargetData, file: SourceFile): TypeResolver
}

/**
 * Groups declarations into type nodes. Resolution of a simple name goes through the declaring target first,
 * then through the project targets the file imports; an ambiguous name resolves to nothing, because a missing edge is better than a false one.
 */
function collectTypes(targets: readonly TargetData[], byName: ReadonlyMap<string, TargetData>): TypeIndex {
  const entries: TypeEntry[] = []
  const extensions = new Map<string, TypeEntry>()
  const resolvers = new Map<SourceFile, TypeResolver>()

  const resolverOf = (target: TargetData, file: SourceFile): TypeResolver => {
    const cached = resolvers.get(file)
    if (cached) return cached
    const imported = [...new Set(file.parsed.imports.map((entry) => entry.module))]
      .map((module) => byName.get(module))
      .filter((candidate): candidate is TargetData => candidate !== undefined && candidate !== target)
    const memo = new Map<string, string | null>()
    const resolver: TypeResolver = (name) => {
      const known = memo.get(name)
      if (known !== undefined) return known
      const own = target.types.get(name)?.id
      let result: string | null = own ?? null
      if (!own) {
        const candidates = [...new Set(imported.flatMap((candidate) => candidate.types.get(name)?.id ?? []))]
        result = candidates.length === 1 ? (candidates[0] as string) : null
      }
      memo.set(name, result)
      return result
    }
    resolvers.set(file, resolver)
    return resolver
  }

  const contributionOf = (target: TargetData, file: SourceFile, declaration: SwiftDeclaration): Contribution => ({ file, declaration, resolve: resolverOf(target, file) })

  for (const target of targets) {
    for (const file of target.files) {
      for (const declaration of file.parsed.declarations) {
        if (declaration.flavor === 'extension') continue
        const existing = target.types.get(declaration.name)
        // The same name twice in one target (`#if` branches) is merged: ids must stay unique.
        if (existing) {
          existing.contributions.push(contributionOf(target, file, declaration))
          continue
        }
        const entry: TypeEntry = {
          id: `ios:type:${target.manifest.name}.${declaration.name}`,
          target,
          name: declaration.name,
          flavor: declaration.flavor,
          extensionOf: null,
          contributions: [contributionOf(target, file, declaration)],
        }
        target.types.set(declaration.name, entry)
        entries.push(entry)
      }
    }
  }
  for (const target of targets) {
    for (const file of target.files) {
      for (const declaration of file.parsed.declarations) {
        if (declaration.flavor !== 'extension') continue
        const base = declaration.name.split('.')[0] as string
        const own = target.types.get(base)
        if (own) {
          own.contributions.push(contributionOf(target, file, declaration))
          continue
        }
        const key = `${target.manifest.name}.${declaration.name}`
        const existing = extensions.get(key)
        if (existing) {
          existing.contributions.push(contributionOf(target, file, declaration))
          continue
        }
        const entry: TypeEntry = {
          id: `ios:ext:${key}`,
          target,
          name: declaration.name,
          flavor: 'extension',
          extensionOf: declaration.name,
          contributions: [contributionOf(target, file, declaration)],
        }
        extensions.set(key, entry)
        entries.push(entry)
      }
    }
  }

  return {
    all: () => entries,
    byTarget: (target) => entries.filter((entry) => entry.target === target),
    resolverOf,
  }
}

/** `Module.Type` names a type of a project target; a plain name goes through the file's resolver. */
function resolveQualified(name: string, resolveType: TypeResolver, byName: ReadonlyMap<string, TargetData>): string | null {
  const [first, second, ...rest] = name.split('.')
  if (second === undefined) return resolveType(name)
  const module = byName.get(first as string)
  if (!module || rest.length > 0) return null
  return module.types.get(second)?.id ?? null
}

function functionFactsOf(nodeId: string, ownerTypeId: string, contribution: Contribution, member: SwiftMember): FunctionFacts {
  return {
    nodeId,
    ownerTypeId,
    path: contribution.file.repoPath,
    localTypes: member.localTypes,
    calls: member.calls,
    resolveType: contribution.resolve,
  }
}

function entryKindOf(member: SwiftMember): EntryKind | null {
  if (member.name === 'body') return 'lifecycle'
  if (member.keyword !== 'func') return null
  return LIFECYCLE_NAME.test(member.name) ? 'lifecycle' : 'other'
}

function isGenerated(files: readonly string[]): boolean {
  if (files.length === 0) return false
  const marked = files.filter((path) => GENERATED_MARKER.test(readFileSync(path, 'utf8').slice(0, 400))).length
  return marked / files.length >= 0.5
}

function swiftFiles(dir: string): string[] {
  if (!existsSync(dir)) return []
  const found: string[] = []
  const entries = readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))
  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (!SKIPPED_DIRECTORIES.has(entry.name)) found.push(...swiftFiles(join(dir, entry.name)))
    } else if (entry.name.endsWith('.swift')) {
      found.push(join(dir, entry.name))
    }
  }
  return found
}
